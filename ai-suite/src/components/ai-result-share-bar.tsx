"use client";

import * as React from "react";
import { Check, Copy, Download, Loader2 } from "lucide-react";
import { toast } from "sonner";

import { useCopyFeedback } from "@/components/copy-output-button";
import { LinkedInMark } from "@/components/oauth-brand-icons";
import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils";
import { useI18n } from "@/i18n/i18n-provider";

function publicSiteUrl(): string {
  const raw =
    typeof process !== "undefined" && process.env.NEXT_PUBLIC_SITE_URL
      ? process.env.NEXT_PUBLIC_SITE_URL.trim()
      : "";
  if (raw.length > 0) return raw.replace(/\/$/, "");
  return "https://isendai.com";
}

function XLogo({ className }: { className?: string }) {
  return (
    <svg className={className} viewBox="0 0 24 24" aria-hidden fill="currentColor">
      <path d="M18.244 2.25h3.308l-7.227 8.26 8.502 11.24H16.17l-5.214-6.817L4.99 21.75H1.68l7.73-8.835L1.254 2.25H8.08l4.713 6.231zm-1.161 17.52h1.833L7.084 4.126H5.117z" />
    </svg>
  );
}

/** Clipboard body for LinkedIn (composer URL cannot be prefilled). X uses `buildTweetIntentUrl`. */
function buildLinkedInClipboardBody(body: string): string {
  const site = publicSiteUrl();
  const trimmed = body.trim();
  const attribution = `— Generated by isendai.com ${site}`;
  return trimmed.length > 0 ? `${trimmed}\n\n${attribution}` : attribution;
}

function buildTweetIntentUrl(body: string): string {
  const site = publicSiteUrl();
  const suffix = ` — Generated by isendai.com ${site}`;
  const max = 280;
  const budget = Math.max(0, max - suffix.length);
  const trimmed = body.trim();
  const head =
    trimmed.length <= budget ? trimmed : `${trimmed.slice(0, Math.max(0, budget - 1))}…`;
  const full = `${head}${suffix}`;
  return `https://twitter.com/intent/tweet?text=${encodeURIComponent(full)}`;
}

type AiResultShareBarProps = {
  text: string;
  onCopied?: () => void;
};

/**
 * Round actions (copy, X, LinkedIn, IG/TikTok card) for AI result blocks on /success.
 */
export function AiResultShareBar({ text, onCopied }: AiResultShareBarProps) {
  const { t } = useI18n();
  const { isCopied, copyText } = useCopyFeedback(onCopied);
  const captureRef = React.useRef<HTMLDivElement>(null);
  const [downloading, setDownloading] = React.useState(false);

  const shareDisabled = text.trim().length === 0;

  function shareOnX() {
    if (shareDisabled) return;
    const url = buildTweetIntentUrl(text);
    window.open(url, "_blank", "noopener,noreferrer");
  }

  async function shareOnLinkedIn() {
    if (shareDisabled) return;
    const payload = buildLinkedInClipboardBody(text);
    try {
      await navigator.clipboard.writeText(payload);
      toast.success(t("success.shareLinkedInToast"));
      window.open("https://www.linkedin.com/feed/?shareActive=true", "_blank", "noopener,noreferrer");
    } catch {
      toast.error(t("success.shareLinkedInCopyFailed"));
    }
  }

  async function downloadShareCard() {
    const node = captureRef.current;
    if (!node || shareDisabled) return;
    setDownloading(true);
    try {
      const html2canvas = (await import("html2canvas")).default;
      const canvas = await html2canvas(node, {
        scale: 2,
        useCORS: true,
        logging: false,
        backgroundColor: "#0f172a",
      });
      const a = document.createElement("a");
      a.download = `isendai-share-${Date.now()}.png`;
      a.href = canvas.toDataURL("image/png");
      a.rel = "noopener";
      document.body.appendChild(a);
      a.click();
      a.remove();
      toast.success(t("success.downloadSocialToast"));
    } catch {
      toast.error(t("success.downloadSocialFailed"));
    } finally {
      setDownloading(false);
    }
  }

  const roundBtn =
    "size-9 shrink-0 rounded-full p-0 transition-all duration-300 ease-out active:scale-95 sm:size-10 md:size-11";

  return (
    <>
      {/* Off-screen capture tree for html2canvas (must stay painted; do not use opacity:0). */}
      <div
        ref={captureRef}
        className="pointer-events-none fixed left-[-10000px] top-0 z-0 w-[390px] font-sans"
        aria-hidden
      >
        <div className="relative rounded-[28px] bg-gradient-to-br from-violet-950 via-slate-900 to-indigo-950 p-8 pb-14 shadow-2xl ring-1 ring-white/10">
          <div className="rounded-2xl border border-white/15 bg-white/[0.07] p-6 shadow-inner backdrop-blur-xl">
            <p
              className={cn(
                "leading-relaxed text-white/95 whitespace-pre-wrap",
                text.length > 1600 ? "text-xs" : text.length > 800 ? "text-sm" : "text-[15px]"
              )}
            >
              {text}
            </p>
          </div>
          <p className="absolute bottom-5 right-7 text-[11px] font-semibold uppercase tracking-[0.2em] text-white/45">
            isendai.com
          </p>
        </div>
      </div>

      <div className="absolute right-2 top-2 z-10 flex max-w-[calc(100%-0.5rem)] flex-wrap items-center justify-end gap-1 sm:right-3 sm:top-3 sm:flex-nowrap sm:gap-1.5 md:gap-2">
        <Button
          type="button"
          variant="outline"
          className={cn(
            roundBtn,
            "border-white/[0.14] bg-white/[0.06] shadow-sm backdrop-blur-xl",
            "hover:border-violet-500/45 hover:bg-white/[0.1] hover:shadow-[0_0_18px_rgba(139,92,246,0.3)]"
          )}
          onClick={() => void copyText(text)}
          aria-label={isCopied ? t("ui.copied") : t("success.copy")}
          title={t("success.copy")}
        >
          {isCopied ? (
            <Check className="size-4 text-emerald-400" strokeWidth={1.5} aria-hidden />
          ) : (
            <Copy className="size-4 text-indigo-200" aria-hidden />
          )}
        </Button>

        <Button
          type="button"
          variant="secondary"
          disabled={shareDisabled}
          className={cn(
            roundBtn,
            "border border-zinc-800 bg-black text-white shadow-sm",
            "hover:shadow-[0_0_20px_rgba(168,85,247,0.35)] hover:bg-zinc-950 disabled:opacity-40"
          )}
          onClick={shareOnX}
          aria-label={t("success.shareOnXAria")}
          title={t("success.shareOnX")}
        >
          <XLogo className="size-4 sm:size-[18px]" />
        </Button>

        <Button
          type="button"
          variant="secondary"
          disabled={shareDisabled}
          className={cn(
            roundBtn,
            "border-0 bg-[#0A66C2] text-white shadow-sm",
            "hover:bg-[#004182] hover:shadow-[0_0_18px_rgba(10,102,194,0.45)] dark:hover:bg-[#378fe9] disabled:opacity-40"
          )}
          onClick={() => void shareOnLinkedIn()}
          aria-label={t("success.shareOnLinkedInAria")}
          title={t("success.shareOnLinkedIn")}
        >
          <LinkedInMark className="size-[18px] shrink-0 sm:size-5 [&_path]:!fill-white" />
        </Button>

        <Button
          type="button"
          variant="secondary"
          disabled={downloading || shareDisabled}
          className={cn(
            roundBtn,
            "border-0 bg-gradient-to-r from-indigo-500 via-purple-500 to-pink-500 text-white shadow-md",
            "hover:shadow-[0_0_22px_rgba(168,85,247,0.45)] disabled:opacity-60"
          )}
          onClick={() => void downloadShareCard()}
          aria-label={t("success.downloadSocialAria")}
          title={t("success.downloadSocial")}
        >
          {downloading ? (
            <Loader2 className="size-4 animate-spin text-white" aria-hidden />
          ) : (
            <Download className="size-4 text-white" aria-hidden />
          )}
        </Button>
      </div>
    </>
  );
}
