/**
 * Reads tools from src/components/ai-suite/tools-data.ts and asks OpenAI
 * to produce title + description translations for es, fr, de, zh, tr.
 * Writes: src/i18n/generated/tool-translations.ts
 *
 * Usage (from ai-suite/):
 *   node scripts/generate-tool-i18n.mjs
 * Requires: OPENAI_API_KEY in environment or .env.local (loaded manually below).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function loadDotEnv() {
  for (const name of [".env.local", ".env"]) {
    const p = path.join(root, name);
    if (!fs.existsSync(p)) continue;
    const text = fs.readFileSync(p, "utf8");
    for (const line of text.split("\n")) {
      const t = line.trim();
      if (!t || t.startsWith("#")) continue;
      const i = t.indexOf("=");
      if (i <= 0) continue;
      const k = t.slice(0, i).trim();
      let v = t.slice(i + 1).trim();
      if (
        (v.startsWith('"') && v.endsWith('"')) ||
        (v.startsWith("'") && v.endsWith("'"))
      ) {
        v = v.slice(1, -1);
      }
      if (!process.env[k]) process.env[k] = v;
    }
  }
}

function extractTools(ts) {
  const unescape = (s) =>
    s
      .replace(/\\n/g, "\n")
      .replace(/\\"/g, '"')
      .replace(/\\'/g, "'")
      .replace(/\\\\/g, "\\");

  const tools = [];
  const idMatches = [...ts.matchAll(/tool:\s*"([^"]+)"/g)];
  for (let i = 0; i < idMatches.length; i++) {
    const tool = idMatches[i][1];
    const start = idMatches[i].index ?? 0;
    const end =
      i + 1 < idMatches.length ? idMatches[i + 1].index ?? ts.length : ts.length;
    const block = ts.slice(start, end);

    const titleDM = block.match(/title:\s*"((?:\\.|[^"\\])*)"/);
    const titleSM = block.match(/title:\s*'((?:\\.|[^'\\])*)'/);
    const titleRaw = titleDM?.[1] ?? titleSM?.[1];
    if (!titleRaw) throw new Error(`Could not parse title for tool "${tool}"`);

    const descM = block.match(/description:\s*"((?:\\.|[^"\\])*)"/);
    if (!descM) throw new Error(`Could not parse description for tool "${tool}"`);

    tools.push({
      tool,
      title: unescape(titleRaw),
      description: unescape(descM[1]),
    });
  }
  return tools;
}

const LOCALES = ["es", "fr", "de", "zh", "tr"];

async function openaiJson(prompt) {
  const key = process.env.OPENAI_API_KEY;
  if (!key) {
    throw new Error("OPENAI_API_KEY is not set (.env.local or environment).");
  }
  const res = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      "content-type": "application/json",
      authorization: `Bearer ${key}`,
    },
    body: JSON.stringify({
      model: "gpt-4o-mini",
      temperature: 0.2,
      messages: [
        {
          role: "system",
          content:
            "You are a professional product localizer. Return ONLY valid JSON, no markdown.",
        },
        { role: "user", content: prompt },
      ],
    }),
  });
  const json = await res.json().catch(() => ({}));
  if (!res.ok) {
    throw new Error(json?.error?.message || `OpenAI error HTTP ${res.status}`);
  }
  const text = json?.choices?.[0]?.message?.content?.trim() || "";
  return JSON.parse(text);
}

async function translateBatch(toolsSlice, locale, label) {
  const payload = toolsSlice.map((t) => ({
    id: t.tool,
    title: t.title,
    description: t.description,
  }));

  const prompt =
    `Translate the following AI micro-product names (title) and short marketing descriptions (description) into **${label}**.\n` +
    `Rules:\n` +
    `- Keep the same meaning; concise UI copy.\n` +
    `- Do NOT translate proper brands if any; these are generic tools.\n` +
    `- Preserve intent; descriptions are one sentence where possible.\n` +
    `- Output JSON shape: { "items": [ { "id": string, "title": string, "description": string } ] }\n` +
    `- The "id" must match exactly.\n\n` +
    `INPUT:\n${JSON.stringify(payload)}`;

  const out = await openaiJson(prompt);
  if (!out?.items || !Array.isArray(out.items)) {
    throw new Error("Model returned invalid JSON (missing items[]).");
  }
  const map = new Map();
  for (const it of out.items) {
    if (it?.id && typeof it.title === "string" && typeof it.description === "string") {
      map.set(it.id, { title: it.title, description: it.description });
    }
  }
  return map;
}

function toTsFile(allByLocale) {
  let s = `// AUTO-GENERATED by scripts/generate-tool-i18n.mjs — do not edit by hand.\n`;
  s += `import type { Locale } from "@/i18n/dictionaries";\n`;
  s += `import type { ToolName } from "@/components/ai-suite/tools";\n\n`;
  s += `export type ToolCopy = { title: string; description: string };\n\n`;

  for (const loc of LOCALES) {
    s += `const ${loc.toUpperCase()}: Partial<Record<ToolName, ToolCopy>> = {\n`;
    const entries = Object.entries(allByLocale[loc]).sort(([a], [b]) =>
      a.localeCompare(b)
    );
    for (const [id, v] of entries) {
      const title = JSON.stringify(v.title);
      const desc = JSON.stringify(v.description);
      s += `  ${JSON.stringify(id)}: { title: ${title}, description: ${desc} },\n`;
    }
    s += `};\n\n`;
  }

  s += `export const TOOL_TRANSLATIONS: Record<Exclude<Locale, "en">, Partial<Record<ToolName, ToolCopy>>> = {\n`;
  for (const loc of LOCALES) {
    s += `  ${JSON.stringify(loc)}: ${loc.toUpperCase()},\n`;
  }
  s += `};\n`;
  return s;
}

async function main() {
  loadDotEnv();
  const tsPath = path.join(root, "src/components/ai-suite/tools-data.ts");
  const tools = extractTools(fs.readFileSync(tsPath, "utf8"));
  if (tools.length !== 100) {
    throw new Error(`Expected 100 tools, got ${tools.length}`);
  }

  const labels = {
    es: "Spanish (Spain neutral)",
    fr: "French (France)",
    de: "German (Germany)",
    zh: "Simplified Chinese",
    tr: "Turkish",
  };

  const batchSize = 25;
  const allByLocale = { es: {}, fr: {}, de: {}, zh: {}, tr: {} };

  for (let i = 0; i < tools.length; i += batchSize) {
    const slice = tools.slice(i, i + batchSize);
    console.error(`Batch ${i}-${i + slice.length} / ${tools.length}`);
    for (const loc of LOCALES) {
      const m = await translateBatch(slice, loc, labels[loc]);
      for (const t of slice) {
        const got = m.get(t.tool);
        if (!got) {
          throw new Error(`Missing translation for ${t.tool} in ${loc}`);
        }
        allByLocale[loc][t.tool] = got;
      }
      await new Promise((r) => setTimeout(r, 400));
    }
  }

  const outDir = path.join(root, "src/i18n/generated");
  fs.mkdirSync(outDir, { recursive: true });
  const outPath = path.join(outDir, "tool-translations.ts");
  fs.writeFileSync(outPath, toTsFile(allByLocale), "utf8");
  console.error(`Wrote ${path.relative(root, outPath)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
