/**
 * Builds src/i18n/generated/tool-translations.ts using MyMemory (free, no API key).
 * Run from ai-suite/: node scripts/translate-mymemory.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const TARGETS = [
  ["es", "ES"],
  ["fr", "FR"],
  ["de", "DE"],
  ["zh", "ZH"],
  ["tr", "TR"],
];

async function translatePair(title, description, langPair) {
  const combined = `${title}\n---\n${description}`;
  const u = new URL("https://api.mymemory.translated.net/get");
  u.searchParams.set("q", combined.slice(0, 450));
  u.searchParams.set("langpair", `en|${langPair}`);
  const res = await fetch(u);
  const json = await res.json().catch(() => ({}));
  const out = json?.responseData?.translatedText;
  if (!out || json.responseStatus === "403") {
    throw new Error(json?.responseData?.error || "translate failed");
  }
  const parts = String(out).split(/\n---\n/);
  if (parts.length >= 2) {
    return { title: parts[0].trim(), description: parts.slice(1).join("\n---\n").trim() };
  }
  return { title: String(out).trim(), description: description };
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function toTs(allByLocale) {
  let s = `// AUTO-GENERATED by scripts/translate-mymemory.mjs\n`;
  s += `import type { Locale } from "@/i18n/dictionaries";\n`;
  s += `import type { ToolName } from "@/components/ai-suite/tools";\n\n`;
  s += `export type ToolCopy = { title: string; description: string };\n\n`;

  for (const [loc] of TARGETS) {
    s += `const ${loc.toUpperCase()}: Partial<Record<ToolName, ToolCopy>> = {\n`;
    const entries = Object.entries(allByLocale[loc]).sort(([a], [b]) =>
      a.localeCompare(b)
    );
    for (const [id, v] of entries) {
      s += `  ${JSON.stringify(id)}: { title: ${JSON.stringify(v.title)}, description: ${JSON.stringify(v.description)} },\n`;
    }
    s += `};\n\n`;
  }

  s += `export const TOOL_TRANSLATIONS: Record<Exclude<Locale, "en">, Partial<Record<ToolName, ToolCopy>>> = {\n`;
  for (const [loc] of TARGETS) {
    s += `  ${JSON.stringify(loc)}: ${loc.toUpperCase()},\n`;
  }
  s += `};\n`;
  return s;
}

async function main() {
  const tools = JSON.parse(
    fs.readFileSync(path.join(root, "tools-en.json"), "utf8")
  );
  if (!Array.isArray(tools) || tools.length !== 100) {
    throw new Error("tools-en.json must contain 100 tools");
  }

  const allByLocale = { es: {}, fr: {}, de: {}, zh: {}, tr: {} };

  for (const [loc, pair] of TARGETS) {
    console.error(`Locale ${loc}...`);
    for (const t of tools) {
      const { title, description } = await translatePair(
        t.title,
        t.description,
        pair
      );
      await sleep(350);
      allByLocale[loc][t.tool] = { title, description };
      console.error(`  ${t.tool}`);
    }
  }

  const outDir = path.join(root, "src/i18n/generated");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "tool-translations.ts"), toTs(allByLocale), "utf8");
  console.error("Done.");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
